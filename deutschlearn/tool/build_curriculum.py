#!/usr/bin/env python3
"""Builds the curriculum seed migration from supabase/curriculum/**/*.yaml.

Each YAML file is one module:

  module: {slug, level, position, icon, title_de, title_ar, description_ar}
  lessons:
    - slug, kind (lesson|test|exam|placement), title_de, title_ar, goal_ar,
      explanation_ar, pass_percent (default 70)
      items: one key names the kind; the correct option is always listed first.
        - vocab: "der Tisch, -e"     ar: "طاولة"   ex: "..."  ex_ar: "..."
        - phrase: "Wie geht's?"      ar: "..."
        - text: "Dialog…"            ar: "الترجمة"
        - rule: "شرح بالعربية"        de: "Beispiele"
        - quiz: "السؤال"              de: "optional prompt"  options: [right, wrong, ...]
        - gap: "Ich ___ Ahmed."      ar: "تلميح"  options: [heiße, heißt, ...]
        - listen: "Guten Morgen"     ar: "السؤال"  options: [right, wrong, ...]
        - order: "Ich wohne in Berlin."  ar: "أسكن في برلين."
        - match: ["der Hund = الكلب", ...]  ar: "التعليمات"
        - write: "Ich heiße Anna.|Ich heisse Anna."  ar: "اكتب: اسمي آنا."

Usage: python3 tool/build_curriculum.py   (writes the migration, prints stats)
"""
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'supabase' / 'curriculum'
OUT = ROOT / 'supabase' / 'migrations' / '20261122001000_curriculum_content.sql'

KINDS = ['vocab', 'phrase', 'text', 'rule', 'quiz', 'gap', 'listen', 'order', 'match', 'write']
SCORED = {'quiz', 'gap', 'listen', 'order', 'match', 'write'}
LEGACY = ['Begrüßung', 'Sich vorstellen', 'Zahlen 1–20', 'Die Familie', 'Farben',
          'Essen und Trinken', 'Die Wochentage', 'Die Uhrzeit']


def q(v):
    if v is None:
        return 'null'
    return "'" + str(v).replace("'", "''") + "'"


def fail(where, msg):
    sys.exit(f'{where}: {msg}')


def item_row(where, it):
    kinds = [k for k in KINDS if k in it]
    if len(kinds) != 1:
        fail(where, f'item needs exactly one kind key, got {list(it)}')
    kind = kinds[0]
    main = it[kind]
    german, arabic, ex, ex_ar, options, answer = '', it.get('ar', ''), it.get('ex'), it.get('ex_ar'), None, None
    if kind in ('vocab', 'phrase', 'text', 'order', 'write', 'gap', 'listen'):
        german = str(main).strip()
    if kind == 'rule':
        arabic, german = str(main).strip(), str(it.get('de', '')).strip()
    if kind == 'quiz':
        arabic, german = str(main).strip(), str(it.get('de', '')).strip()
    if kind in ('quiz', 'gap', 'listen'):
        options = [str(o) for o in it.get('options', [])]
        if not 2 <= len(options) <= 8 or len(set(options)) != len(options):
            fail(where, f'{kind} needs 2–8 distinct options')
        answer = 0
        if kind == 'listen' and not arabic:
            arabic = 'استمع واختر المعنى الصحيح'
    if kind == 'gap' and '___' not in german:
        fail(where, 'gap sentence needs ___')
    if kind == 'match':
        options = [str(o) for o in main]
        if not 2 <= len(options) <= 8 or any(o.count(' = ') != 1 for o in options):
            fail(where, 'match needs 2–8 "German = Arabic" pairs')
        arabic = arabic or 'طابق كل كلمة بمعناها'
    if kind == 'order' and len(german.split()) < 2:
        fail(where, 'order sentence needs at least two words')
    if kind in ('write', 'order') and not arabic:
        fail(where, f'{kind} needs an Arabic prompt (ar)')
    if len(german) > 4000 or len(arabic) > 4000:
        fail(where, 'text too long')
    return kind, german, arabic, ex, ex_ar, options, answer


def main():
    files = sorted(SRC.glob('**/*.yaml'))
    if not files:
        sys.exit('no curriculum files')
    out = ['-- GENERATED by tool/build_curriculum.py from supabase/curriculum/. Do not edit by hand.',
           '-- Idempotent: modules and lessons are upserted by slug; their items are replaced.',
           'do $$', 'declare m uuid; l uuid;', 'begin',
           '  delete from public.lessons where module_id is null and slug is null and title_de in ('
           + ', '.join(q(t) for t in LEGACY) + ');']
    slugs, stats = set(), {'modules': 0, 'lessons': 0, 'items': 0, 'words': 0}
    for f in files:
        doc = yaml.safe_load(f.read_text(encoding='utf-8'))
        mod = doc['module']
        where = f.relative_to(ROOT)
        for k in ('slug', 'level', 'position', 'title_de', 'title_ar'):
            if k not in mod:
                fail(where, f'module.{k} missing')
        if mod['slug'] in slugs:
            fail(where, 'duplicate slug ' + mod['slug'])
        slugs.add(mod['slug'])
        stats['modules'] += 1
        out.append(
            '  insert into public.modules (slug, cefr_level, position, title_de, title_ar, description_ar, icon) values ('
            + ', '.join([q(mod['slug']), q(mod['level']), str(int(mod['position'])), q(mod['title_de']),
                         q(mod['title_ar']), q(mod.get('description_ar', '')), q(mod.get('icon', 'book'))])
            + ') on conflict (slug) do update set cefr_level = excluded.cefr_level, position = excluded.position,'
            + ' title_de = excluded.title_de, title_ar = excluded.title_ar, description_ar = excluded.description_ar,'
            + ' icon = excluded.icon returning id into m;')
        for pos, les in enumerate(doc.get('lessons', []), start=1):
            lw = f'{where} lesson {pos}'
            if les.get('slug') in slugs or not re.fullmatch(r'[a-z0-9-]+', les.get('slug', '')):
                fail(lw, f"bad or duplicate slug {les.get('slug')}")
            slugs.add(les['slug'])
            kind = les.get('kind', 'lesson')
            if kind not in ('lesson', 'test', 'exam', 'placement'):
                fail(lw, 'bad kind')
            rows = [item_row(f'{lw} item {i}', it) for i, it in enumerate(les.get('items', []), start=1)]
            scored = sum(1 for r in rows if r[0] in SCORED)
            if scored == 0 or scored > 100:
                fail(lw, f'needs 1–100 scored exercises, has {scored}')
            stats['lessons'] += 1
            stats['items'] += len(rows)
            stats['words'] += sum(1 for r in rows if r[0] == 'vocab')
            out.append(
                '  insert into public.lessons (slug, module_id, cefr_level, position, kind, title_de, title_ar,'
                ' description_ar, goal_ar, explanation_ar, pass_percent) values ('
                + ', '.join([q(les['slug']), 'm', q(mod['level']), str(int(mod['position']) * 100 + pos), q(kind),
                             q(les['title_de']), q(les.get('title_ar', '')), q(les.get('description_ar', '')),
                             q(les.get('goal_ar', '')), q(str(les.get('explanation_ar', '')).strip()),
                             str(int(les.get('pass_percent', 70)))])
                + ') on conflict (slug) do update set module_id = excluded.module_id, cefr_level = excluded.cefr_level,'
                + ' position = excluded.position, kind = excluded.kind, title_de = excluded.title_de,'
                + ' title_ar = excluded.title_ar, description_ar = excluded.description_ar, goal_ar = excluded.goal_ar,'
                + ' explanation_ar = excluded.explanation_ar, pass_percent = excluded.pass_percent returning id into l;')
            out.append('  delete from public.lesson_items where lesson_id = l;')
            values = []
            for i, (k, de, ar, ex, ex_ar, opts, ans) in enumerate(rows, start=1):
                values.append('    (l, ' + ', '.join([
                    str(i), q(k), q(de), q(ar), q(ex), q(ex_ar),
                    'null' if opts is None else q(json.dumps(opts, ensure_ascii=False)) + '::jsonb',
                    'null' if ans is None else str(ans)]) + ')')
            out.append('  insert into public.lesson_items (lesson_id, position, kind, german, arabic, example_de,'
                       ' example_ar, options, answer) values\n' + ',\n'.join(values) + ';')
    out += ['end', '$$;', '']
    OUT.write_text('\n'.join(out), encoding='utf-8')
    print(f"{OUT.relative_to(ROOT)}: {stats}")


if __name__ == '__main__':
    main()
